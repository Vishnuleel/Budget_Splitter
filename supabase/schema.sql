-- Splitkvitto — Supabase schema (multi-user, with an admin)
-- Run in Supabase → SQL Editor → New query. Safe to run again at any time.
--
-- Order for a new project (see docs/ACCOUNTS.md):
--   1. Authentication → Sign In / Providers: turn OFF "Allow new users to sign up".
--   2. Authentication → Users → Add user: create YOURSELF (email + password, auto-confirm).
--   3. Run this file. The first user becomes the admin, and any rows from the old
--      single-user version are given to that admin.

-- ── People ───────────────────────────────────────────────────
create table if not exists public.profiles (
  id                   uuid primary key references auth.users(id) on delete cascade,
  email                text,
  display_name         text,
  role                 text not null default 'member' check (role in ('admin', 'member')),
  disabled             boolean not null default false,
  sms_token_hash       text unique,          -- sha256 of the person's personal SMS key
  sms_token_created_at timestamptz,
  created_at           timestamptz not null default now()
);

-- New auth user → profile. The very first person becomes admin.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, display_name, role)
  values (
    new.id,
    new.email,
    coalesce(nullif(new.raw_user_meta_data->>'display_name', ''), split_part(new.email, '@', 1)),
    case when exists (select 1 from public.profiles where role = 'admin') then 'member' else 'admin' end
  )
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Users created before this file ran (e.g. you, in step 2) get a profile too.
insert into public.profiles (id, email, display_name)
select u.id, u.email, split_part(u.email, '@', 1) from auth.users u
on conflict (id) do nothing;

-- Make sure someone is admin: the oldest account, if nobody is yet.
update public.profiles set role = 'admin'
where id = (select id from public.profiles order by created_at limit 1)
  and not exists (select 1 from public.profiles where role = 'admin');

-- Used by every policy: signed in AND not paused by the admin.
create or replace function public.is_active_user()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and not disabled)
$$;

