-- ── "Pick your items" links for shared receipts ──────────────
-- Roommates open a link (no account needed). Only the SHA-256 of the link's secret is stored.
-- All reads/writes go through /api/bill with the service role; owners may read their own rows.
create table if not exists public.bill_shares (
  id         uuid primary key default gen_random_uuid(),
  owner_id   uuid not null references auth.users(id) on delete cascade,
  token_hash text not null unique,
  bill       jsonb not null,
  claims     jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default now() + interval '30 days'
);
create index if not exists bill_shares_owner_idx on public.bill_shares (owner_id);
alter table public.bill_shares enable row level security;
drop policy if exists bill_shares_owner_read on public.bill_shares;
create policy bill_shares_owner_read on public.bill_shares for select to authenticated using (owner_id = auth.uid());
revoke all on public.bill_shares from anon;
revoke insert, update, delete on public.bill_shares from authenticated;

-- ── Friends + bills sent straight into friends' accounts ─────
-- All reads and writes go through /api/shared with the service role, which enforces the rules
-- (only connected friends, only the payer approves changes, paid only when the payer confirms).
-- Row Level Security is on with no policies for signed-in users, so the tables can't be read or
-- changed directly from the app — not even your own rows.
create table if not exists public.friendships (
  id         uuid primary key default gen_random_uuid(),
  requester  uuid not null references auth.users(id) on delete cascade,
  addressee  uuid not null references auth.users(id) on delete cascade,
  status     text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at timestamptz not null default now(),
  check (requester <> addressee)
);
-- One row per pair, whichever direction it was asked in.
create unique index if not exists friendships_pair_idx
  on public.friendships (least(requester, addressee), greatest(requester, addressee));
create index if not exists friendships_addressee_idx on public.friendships (addressee);
create index if not exists friendships_requester_idx on public.friendships (requester);

create table if not exists public.shared_bills (
  id         uuid primary key default gen_random_uuid(),
  owner      uuid not null references auth.users(id) on delete cascade,
  bill       jsonb not null,
  members    jsonb not null,             -- [{ user_id, status, removed, note, reply, paid, ack_total }]
  member_ids uuid[] not null,            -- for "bills I'm on" lookups
  version    integer not null default 1, -- optimistic locking: two people acting at once never overwrite each other
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists shared_bills_owner_idx on public.shared_bills (owner);
create index if not exists shared_bills_members_idx on public.shared_bills using gin (member_ids);

alter table public.friendships enable row level security;
alter table public.shared_bills enable row level security;
revoke all on public.friendships from anon, authenticated;
revoke all on public.shared_bills from anon, authenticated;
