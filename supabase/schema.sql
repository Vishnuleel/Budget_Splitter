-- ── Upgrading a database from the single-user version ────────
do $$
declare
  t text;
  has_orphans boolean;
  owner_id uuid := (select id from public.profiles where role = 'admin' order by created_at limit 1);
begin
  foreach t in array array['transactions','accounts','vaults','deposits','debts','subscriptions'] loop
    execute format('alter table public.%I add column if not exists currency text not null default %L', t, 'INR');
    execute format('alter table public.%I add column if not exists user_id uuid default auth.uid() references auth.users(id) on delete cascade', t);
    if owner_id is not null then
      execute format('update public.%I set user_id = %L where user_id is null', t, owner_id);
    end if;
    -- Only enforce NOT NULL once every old row has an owner (re-run after creating your user if needed).
    if not exists (select 1 from information_schema.columns
                   where table_schema = 'public' and table_name = t and column_name = 'user_id' and is_nullable = 'NO') then
      -- (EXECUTE doesn't set FOUND, so read the answer into a variable.)
      execute format('select exists (select 1 from public.%I where user_id is null)', t) into has_orphans;
      if not has_orphans then
        execute format('alter table public.%I alter column user_id set not null', t);
      end if;
    end if;
  end loop;

  -- Old app_settings had one global row per key.
  if not exists (select 1 from information_schema.columns
                 where table_schema = 'public' and table_name = 'app_settings' and column_name = 'user_id') then
    alter table public.app_settings add column user_id uuid default auth.uid() references auth.users(id) on delete cascade;
    if owner_id is not null then update public.app_settings set user_id = owner_id where user_id is null; end if;
    delete from public.app_settings where user_id is null;
    alter table public.app_settings drop constraint if exists app_settings_pkey;
    alter table public.app_settings alter column user_id set not null;
    alter table public.app_settings add primary key (user_id, key);
  end if;
end $$;

