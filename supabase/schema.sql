-- ── Row Level Security: everyone sees only their own rows ────
do $$
declare t text;
begin
  foreach t in array array['transactions','accounts','vaults','deposits','debts','subscriptions','app_settings'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists owner_only on public.%I', t);
    execute format('drop policy if exists own_rows on public.%I', t);
    execute format($p$create policy own_rows on public.%I for all to authenticated
                     using (user_id = auth.uid() and public.is_active_user())
                     with check (user_id = auth.uid() and public.is_active_user())$p$, t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;

-- A transaction may only point at one of your own accounts (FK checks skip RLS,
-- so without this anyone could attach rows to another person's account id).
create index if not exists transactions_account_idx on public.transactions (account_id);
drop policy if exists tx_own_account on public.transactions;
create policy tx_own_account on public.transactions as restrictive for all to authenticated
  using (true)
  with check (account_id is null or exists (
    select 1 from public.accounts a where a.id = account_id and a.user_id = auth.uid()));

-- Profiles: read your own; change only your display name and SMS key.
-- Role / paused / deleting accounts happen through the admin API (service role).
alter table public.profiles enable row level security;
drop policy if exists profiles_self_read on public.profiles;
drop policy if exists profiles_self_update on public.profiles;
create policy profiles_self_read on public.profiles for select to authenticated using (id = auth.uid());
create policy profiles_self_update on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());
revoke all on public.profiles from anon;
revoke insert, update, delete on public.profiles from authenticated;
grant select on public.profiles to authenticated;
grant update (display_name, sms_token_hash, sms_token_created_at) on public.profiles to authenticated;

-- Admin portal stats: counts only, never amounts.
create or replace function public.admin_user_stats()
returns table (user_id uuid, tx_count bigint, last_tx_at timestamptz, last_sms_at timestamptz)
language sql stable security definer set search_path = public as $$
  select t.user_id, count(*), max(t.date), max(t.date) filter (where t.raw_text is not null)
  from public.transactions t
  group by t.user_id
$$;
revoke all on function public.admin_user_stats() from public, anon, authenticated;
grant execute on function public.admin_user_stats() to service_role;

